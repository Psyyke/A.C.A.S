function getSiteData(dataType, obj) {
    const pathname = window.location.pathname;

    let dataObj = { pathname };

    if(obj && typeof obj === 'object') {
        dataObj = { ...dataObj, ...obj };
    }

    const dataHandlerFunction = supportedSites[domain]?.[dataType];

    if(typeof dataHandlerFunction !== 'function') {
        return null;
    }

    // Sites replace DOM fragments during navigation/animation. An adapter may
    // temporarily have nothing to read; let the next poll retry instead.
    try { return dataHandlerFunction(dataObj); }
    catch(error) { return null; }
}

