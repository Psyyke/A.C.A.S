function updateGameState(basicFenToProcess, boardChanges, forceFen, forcedTurn) {
    const stateHistory = gameStateHistory.get();
    const previousBasicFen = stateHistory[0]?.fen?.basic;
    const isTurnForced = typeof forcedTurn === 'string';

    const previousState = stateHistory[0];
    const positionChanged = previousBasicFen !== basicFenToProcess;
    const observedAt = positionChanged ? Date.now() : previousState?.observedAt ?? Date.now();
    const isTakeback = positionChanged && boardChanges?.movedPieceColor !== previousState?.turn
        && stateHistory.some(state => state.fen?.basic === basicFenToProcess);

    const movedPieceColor = boardChanges?.movedPieceColor;
    const historyGap = ['ambiguous', 'unresolved'].includes(boardChanges.recovery?.status);
    const turn = forcedTurn || (historyGap && getSiteData('turn')) || (movedPieceColor === 'w' ? 'b' : movedPieceColor === 'b' ? 'w' :
        getSiteData('turn') || stateHistory[0]?.turn || 'w');

    const isStandardChessBoard =
        lastBoardRanks === 8 &&
        lastBoardFiles === 8;

    const movedPiece =
        boardChanges?.movedPiece;

    const isCapture =
        boardChanges.pieceAmountChange === -1;

    const isPawnMove =
        movedPiece?.toLowerCase() === 'p';

    const isCastling =
        isStandardChessBoard &&
        boardChanges?.changedSquaresAmount === 4 &&
        movedPiece?.toLowerCase() === 'k' &&
        boardChanges.movedPieces.some(piece =>
            piece.toLowerCase() === 'r'
        );

    const castlingSide =
        isCastling
            ? movedPiece === 'K'
                ? 'white'
                : 'black'
            : null;

    const isDoublePawnPush =
        isPawnMove &&
        boardChanges.from &&
        boardChanges.to &&
        Math.abs(
            Number(boardChanges.from[1]) -
            Number(boardChanges.to[1])
        ) === 2;

    const enPassantTarget =
        isDoublePawnPush
            ? `${boardChanges.from[0]}${
                (
                    Number(boardChanges.from[1]) +
                    Number(boardChanges.to[1])
                ) / 2
            }`
            : '-';

    const isWhiteKingMove =
        movedPiece === 'K';

    const isBlackKingMove =
        movedPiece === 'k';

    const isWhiteKingsideRookMove =
        movedPiece === 'R' &&
        boardChanges.from === 'h1';

    const isWhiteQueensideRookMove =
        movedPiece === 'R' &&
        boardChanges.from === 'a1';

    const isBlackKingsideRookMove =
        movedPiece === 'r' &&
        boardChanges.from === 'h8';

    const isBlackQueensideRookMove =
        movedPiece === 'r' &&
        boardChanges.from === 'a8';

    const isWhiteKingsideRookCapture =
        boardChanges.capturedPiece === 'R' &&
        boardChanges.capturedSquare === 'h1';

    const isWhiteQueensideRookCapture =
        boardChanges.capturedPiece === 'R' &&
        boardChanges.capturedSquare === 'a1';

    const isBlackKingsideRookCapture =
        boardChanges.capturedPiece === 'r' &&
        boardChanges.capturedSquare === 'h8';

    const isBlackQueensideRookCapture =
        boardChanges.capturedPiece === 'r' &&
        boardChanges.capturedSquare === 'a8';

    const halfmoveClock =
        isCapture || isPawnMove
            ? 0
            : gameState.halfmoveClock + 1;

    const plyCount =
        gameState.plyCount + 1;

    const fullmoveNumber =
        Math.floor((plyCount / 2) + 1);

    const loseCastlingRights = (...rights) => {
        for(const right of rights) {
            if(!gameState.lostCastlingRights.includes(right)) {
                gameState.lostCastlingRights.push(right);
            }
        }
    };

    // First state of this match (e.g. page loaded mid-game)
    // Derive the impossible castling rights from the board itself.
    if(!stateHistory.length) seedLostCastlingRights(basicFenToProcess);
    
    if(isWhiteKingMove) loseCastlingRights('K', 'Q');
    if(isBlackKingMove) loseCastlingRights('k', 'q');

    if(isWhiteKingsideRookMove || isWhiteKingsideRookCapture) loseCastlingRights('K');
    if(isWhiteQueensideRookMove || isWhiteQueensideRookCapture) loseCastlingRights('Q');
    if(isBlackKingsideRookMove || isBlackKingsideRookCapture) loseCastlingRights('k');
    if(isBlackQueensideRookMove || isBlackQueensideRookCapture) loseCastlingRights('q');

    const castlingRights =
        isStandardChessBoard
            ? ['K', 'Q', 'k', 'q']
                .filter(right => !gameState.lostCastlingRights.includes(right))
                .join('') || '-'
            : '-';

    // Only time a reply if the beginning of the opponent's turn was observed.
    // Refreshes preserve the timestamp; takebacks and skipped positions are not samples.
    const turnStartedByMove = positionChanged
        ? Boolean(!historyGap && !forceFen && movedPieceColor && (!previousState || previousState.turn === movedPieceColor)
            && !isTakeback && !boardChanges.missedFen && boardChanges.changedSquaresAmount <= 4)
        : previousState?.turnStartedByMove ?? false;
    const completeOpponentTurn = positionChanged && !historyGap && !forceFen && !isTakeback && previousState?.turnStartedByMove
        && previousState.turn === movedPieceColor && movedPieceColor !== getPlayerColor()
        && ['w', 'b'].includes(movedPieceColor) && !boardChanges.missedFen
        && boardChanges.changedSquaresAmount <= 4;
    const moveTime = observedAt - previousState?.observedAt;
    const opponentMoveTime = isTakeback ? null : completeOpponentTurn && moveTime > 0
        ? moveTime : previousState?.opponentMoveTime ?? null;

    const stateObj = {
        observedPly: forceFen && previousState && isTurnForced ? undefined : getSiteData('ply'),
        historyIncomplete: Boolean(previousState?.historyIncomplete || historyGap),
        observedAt,
        turnStartedByMove,
        opponentMoveTime,
        turn,
        movedPiece,
        enPassantTarget,
        castlingRights,
        isCapture,
        isPawnMove,
        isCastling,
        castlingSide,
        halfmoveClock,
        plyCount,
        fullmoveNumber,
        boardChanges,
        'pieceAmountChange': boardChanges.pieceAmountChange
    };

    const currentFullFen = getFen(
        false,
        turn,
        basicFenToProcess,
        stateObj
    );

    const currentBasicFen = currentFullFen?.split(' ', 1)?.[0];

    stateObj.fen = {
        'full': currentFullFen,
        'basic': currentBasicFen
    };

    const tempStateHistory = [
        structuredClone(stateObj),
        ...stateHistory
    ];

    const filteredStateHistory = removeTakeback(tempStateHistory);
    const currentStateObj = filteredStateHistory?.[0];

    Object.assign(gameState, currentStateObj);
    gameStateHistory.set(filteredStateHistory);
}

async function processBoardPosition() {
    const observedBoardElem = chessBoardElem;
    if(!observedBoardElem?.isConnected || getBoardElem() !== observedBoardElem) return;
    clearVisuals({ noMetricsRemoval: true });

    const stateHistory = gameStateHistory.get();
    const latestState = stateHistory[0];
    const squareChangeAmount = latestState?.boardChanges?.changedSquaresAmount || 0;

    updateUserscriptDynamicContext({ gameStart: 0, opponentMoveTime: latestState?.opponentMoveTime ?? null }, gameState?.fen?.full);

    await checkBoardOrientationChange();
    if(chessBoardElem !== observedBoardElem || !observedBoardElem.isConnected || getBoardElem() !== observedBoardElem) return;

    lastMoveRequestTime = Date.now();
    modLastEnteredSquare.squareFen = null;

    if(BoardDrawer)
        BoardDrawer.setBoardDimensions(getBoardDimensions());

    if(!modListeners.length)
        addMovesOnDemandListeners();

    const knownHistoryGap = ['ambiguous', 'unresolved'].includes(latestState?.boardChanges?.recovery?.status)
        && latestState.boardChanges.pieceAmountChange <= 0;
    const observedPly = latestState?.observedPly, previousObservedPly = stateHistory[1]?.observedPly;
    const verifiedForwardObservation = Number.isSafeInteger(observedPly) && observedPly >= 0 &&
        Number.isSafeInteger(previousObservedPly) && previousObservedPly >= 0 && observedPly > previousObservedPly;
    const knownContinuation = ['single', 'unique-within-two-plies'].includes(latestState?.boardChanges?.recovery?.status);
    const isNewMatch = !verifiedForwardObservation && ((squareChangeAmount > 6 && !knownHistoryGap) ||
        (!knownContinuation && defaultPosBasicFens.includes(gameState.fen.basic.replace(/\[[^\]]*\]$/, '')) &&
            squareChangeAmount > 1));

    if(isNewMatch) {
        resetStoredMatchVariables();
        updateUserscriptDynamicContext({ evaluation: null, opponentMoveTime: null, materialBalance: null, gameStart: 1 });

        matchFirstSuggestionGiven = false;
    }

    // Publish the same state after any reset; never derive the turn from orientation.
    setBoardState({ fen: gameState.fen.full, ...(gameState.turn && { turn: gameState.turn }) });
    if(isNewMatch) await CommLink.commands.newMatchStarted(getBoardState());

    await CommLink.commands.updateBoardFen(getBoardState());
}

// This also updates the turn instanceVariable that the GUI uses to determine the turn!
function observeNewMoves() {
    if(boardObserver?.disconnect) boardObserver.disconnect();
    if(dumbBoardObservingInterval) clearInterval(dumbBoardObservingInterval);

    let checking = false;
    let positionPending = false;
    const observedBoardElem = chessBoardElem;
    const checkPosition = () => runUserscriptTask(async () => {
        if(chessBoardElem !== observedBoardElem || !observedBoardElem.isConnected) return;
        positionPending = true;
        if(checking) return;
        checking = true;
        try {
            do {
                positionPending = false;
                await determineBoardPositionValidity();
            } while(positionPending && chessBoardElem === observedBoardElem && observedBoardElem.isConnected);
        }
        finally { checking = false; }
    });

    // A board can settle on its real orientation shortly after it was first read, without any move happening.
    const checkOrientation = () => runUserscriptTask(async () => {
        if(checking || !lastBoardOrientation || getBoardOrientation() === lastBoardOrientation) return;
        checking = true;
        try {
            await checkBoardOrientationChange();
            await CommLink.commands.updateBoardFen(getBoardState());
        } finally {
            checking = false;
            if(positionPending) checkPosition();
        }
    });

    dumbBoardObservingInterval = setInterval(() => {
        if(isUserMouseDown) return;

        checkPosition();
        checkOrientation();
    }, 250);

    boardObserver = new MutationObserver(mutationArr => {
        try {
            lastMutationObservationDate = Date.now();

            // Do not continue if mutation was not detected as a possible new move! (Different for each chess site)
            // We later compare FENs to detect if it was actually a new valid move!
            if(!isMutationNewMove(mutationArr)) return;

            checkPosition();
        } catch(e) {
            if(debugModeActivated) console.error(e);
        }
    });

    boardObserver.observe(chessBoardElem, { childList: true, subtree: true, attributes: true });
}

async function checkBoardOrientationChange(forceUpdate = false) {
    const boardOrientation = getBoardOrientation();
    const playerColor = getPlayerColor();

    // Identity can become available after the board, without an orientation change.
    if(boardState.playerColor !== playerColor)
        setBoardState({ playerColor });

    const boardOrientationChanged = lastBoardOrientation !== boardOrientation;
    const boardOrientationDiffers = BoardDrawer && BoardDrawer?.orientation !== boardOrientation;

    if(forceUpdate || boardOrientationChanged || boardOrientationDiffers) {
        lastBoardOrientation = boardOrientation;

        setBoardState({ boardOrientation });

        if(BoardDrawer) BoardDrawer.setOrientation(boardOrientation);

        await CommLink.commands.updateBoardOrientation(boardOrientation);
    }

    return boardOrientationChanged;
}

